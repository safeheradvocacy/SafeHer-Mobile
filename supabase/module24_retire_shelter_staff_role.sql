-- ---------------------------------------------------------
-- 1. The actual migration — convert every existing shelter_staff
--    account to shelter_admin, same shelter, same everything else.
-- ---------------------------------------------------------
update public.user_profiles
set role = 'shelter_admin'
where role = 'shelter_staff';



import jsPDF from 'jspdf';
import {
  MARGIN,
  DEFAULT_CONFIDENTIALITY_NOTE,
  drawBrandHeader,
  drawMetaBlock,
  executiveSummaryTable,
  chartImageSection,
  drawAppliedFilters,
  finalizePagination,
  ensureSpace,
  reportingPeriodLabel,
  setSafeSpaceDocumentMetadata,
  type DistributionRow,
} from './reportDocument';

/**
 * Analytics-specific PDF document (the brief's "Analytics PDF" is
 * explicitly NOT the Reporting PDF — it carries KPIs + the actual
 * charts shown on the Analytics page, not case-record tables). Built
 * entirely from reportDocument.ts's shared primitives (brand header,
 * meta block, executive summary, applied filters, pagination/footer,
 * and the new chartImageSection) — this file adds zero new drawing
 * logic of its own beyond composing those, the same relationship
 * generateRoleReportPdf already has with that file for role reports.
 *
 * Deliberately does NOT draw a signatory/certification block (that's a
 * Reporting-document concept — see reportDocument.ts's own note on
 * generateRoleReportPdf) and does NOT include case-record detail
 * tables (that's what the Reports PDF is for). An Analytics PDF is a
 * snapshot of the dashboard's charts/KPIs for the caller's own
 * authorized, already-filtered data — never an independent
 * recalculation.
 */

export interface AnalyticsChartSection {
  title: string;
  /** The REAL captured <canvas> image (captureChartImage.ts) — null
   * when the chart was empty/not rendered on screen, in which case
   * chartImageSection falls back to the table alone rather than a
   * broken image. */
  image: { dataUrl: string; width: number; height: number } | null;
  /** The same {label,count} rows already driving the on-screen chart —
   * never recalculated here. Null (not just []) means "this metric has
   * no table counterpart"; [] means "computed, but currently empty". */
  tableRows: DistributionRow[] | null;
  valueLabel?: string;
}

export interface AnalyticsPdfParams {
  /** Short ALL-CAPS line under the SAFESPACE wordmark, e.g. "CASE ANALYTICS REPORT". */
  documentKicker: string;
  /** The large document title, e.g. "Case Analytics". */
  reportTitle: string;
  /** Compact running header repeated on page 2+. */
  runningHeaderTitle: string;
  /** Footer line repeated on every page. */
  footerLabel: string;
  generatedByName: string;
  generatedByRole: string;
  /** Authorized reporting scope/jurisdiction — e.g. "Barangay San Luis, Baler" — sourced from the viewer's own verified profile/role, never a client-editable field. */
  scopeLabel: string;
  dateFrom: string;
  dateTo: string;
  appliedFilterLines: string[];
  /** Executive-summary KPI label/value rows (the same numbers shown as KpiCards on screen). Omit the section by passing []. */
  kpis: DistributionRow[];
  /** Zero or more chart sections, in the same order they appear on the Analytics page. */
  charts: AnalyticsChartSection[];
  confidentialityNote?: string;
}

export function generateAnalyticsPdf(params: AnalyticsPdfParams): jsPDF {
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  const generatedAt = new Date();
  setSafeSpaceDocumentMetadata(doc, params.reportTitle, `SafeSpace ${params.documentKicker.toLowerCase()}`);

  let y = drawBrandHeader(doc, MARGIN, params.documentKicker);

  const metaLines: [string, string][] = [
    ['Reporting Period', reportingPeriodLabel(params.dateFrom, params.dateTo)],
    ['Generated', generatedAt.toLocaleString(undefined, { dateStyle: 'long', timeStyle: 'short' })],
    ['Generated By', `${params.generatedByName} (${params.generatedByRole})`],
    ['Scope', params.scopeLabel],
  ];

  y = drawMetaBlock(doc, y, params.reportTitle, metaLines, params.confidentialityNote ?? DEFAULT_CONFIDENTIALITY_NOTE);

  if (params.kpis.length > 0) {
    y = ensureSpace(doc, y, 30);
    y = executiveSummaryTable(doc, y, params.kpis);
  }

  for (const chart of params.charts) {
    y = ensureSpace(doc, y, 40);
    y = chartImageSection(doc, y, chart.title, chart.image, chart.tableRows, chart.valueLabel ?? 'Count');
  }

  y = ensureSpace(doc, y, 14 + params.appliedFilterLines.length * 5);
  drawAppliedFilters(doc, y, params.appliedFilterLines);

  finalizePagination(doc, {
    runningHeaderTitle: params.runningHeaderTitle,
    runningHeaderRight: params.reportTitle,
    footerLeft: params.footerLabel,
  });

  return doc;
}
